// @ts-check

/**
 * Bundles the ZQL benchmarks into a single self-contained file the Expo app in
 * `rn/` imports. Metro never resolves monorepo TypeScript; it only sees the
 * output of this build.
 */
import * as path from 'node:path';
import {fileURLToPath} from 'node:url';
import * as esbuild from 'esbuild';
import {makeDefine, sharedOptions} from '../../shared/src/build.ts';

const dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.join(dirname, '..');
const shimPath = path.join(
  rootDir,
  '..',
  '..',
  'tools',
  'rn-bench',
  'src',
  'mitata-shim.ts',
);

/**
 * Two rewrites make the existing `.bench.ts` files runnable on a device:
 *
 * 1. `shared/src/bench.ts` wraps mitata and Vitest, neither of which runs on
 *    Hermes, so it is replaced by the shim.
 * 2. Each `.bench.ts` module gets a preamble naming itself, so benchmarks from
 *    different files land in different groups. Several files declare a suite
 *    called `push`, which would otherwise collide.
 */
const benchShimPlugin: esbuild.Plugin = {
  name: 'rn-bench-shim',
  setup(build) {
    build.onResolve({filter: /shared\/src\/bench\.ts$/}, () => ({
      path: shimPath,
    }));

    build.onLoad({filter: /\.bench\.ts$/}, async args => {
      const source = await import('node:fs/promises').then(fs =>
        fs.readFile(args.path, 'utf-8'),
      );
      const name = path.basename(args.path).replace(/\.bench\.ts$/, '');
      return {
        contents:
          `import {__setBenchFile as __sbf} from ${JSON.stringify(shimPath)};\n` +
          `__sbf(${JSON.stringify(name)});\n` +
          source,
        loader: 'ts',
        resolveDir: path.dirname(args.path),
      };
    });
  },
};

async function buildRN(): Promise<void> {
  // Minified by default to match what a real app would ship, but Hermes CPU
  // profiles are unreadable without function names.
  const minify = process.env.PERF_RN_NO_MINIFY !== '1';
  await esbuild.build({
    ...sharedOptions(minify),
    external: ['node:*'],
    format: 'esm',
    platform: 'neutral',
    // 'neutral' resolves no main fields at all, so any dependency that ships
    // only a legacy entry (rather than an `exports` map esbuild can follow)
    // fails to resolve outright. Same order replicache-perf uses: what Metro
    // would pick, with `module` ahead of `main` so an ESM build wins where
    // Metro would have fallen back to CommonJS.
    mainFields: ['react-native', 'browser', 'module', 'main'],
    splitting: false,
    plugins: [benchShimPlugin],
    define: {
      ...makeDefine('release'),
      'import.meta.env': 'undefined',
      // Hermes cannot parse import.meta at all.
      'import.meta.url': '""',
    },
    outfile: path.join(rootDir, 'out', 'rn.js'),
    entryPoints: [path.join(rootDir, 'src', 'rn.ts')],
  });
}

/**
 * The declaration for the bundle, emitted beside it so the host app's copy is
 * build output rather than a file kept in step by hand.
 */
async function buildRNTypes(): Promise<void> {
  const fs = await import('node:fs/promises');
  await fs.writeFile(
    path.join(rootDir, 'out', 'rn.d.ts'),
    `// Generated by tool/build-rn.ts from src/rn.ts. Do not edit.

/** Opaque to the host app: it formats results and posts them back. */
export type BenchmarkResult = {readonly __benchmarkResult: unique symbol};

export declare function configure(opts?: unknown): void;
export declare function formatAsReplicache(result: BenchmarkResult): string;
export declare function runBenchmarkByNameAndGroup(
  name: string,
  group: string,
): Promise<['result', BenchmarkResult] | ['error', unknown] | undefined>;
`,
  );
}

await buildRN();
await buildRNTypes();
